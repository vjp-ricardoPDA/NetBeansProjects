public class Operaciones {
    public static int sumar(int n1, int n2){
        return n1 + n2;
    }
    
    public static int restar (int n1, int n2){
        return n1 - n2;
    }
    
    public static int multiplicar (int n1, int n2){
        return n1 * n2;
    }
    
    public static double dividir (int n1, int n2){
        return n1 / n2;
    }
    
    
    
}
